import {
  borderWidth,
  breakpoints,
  colorThemes,
  controlHeight,
  durations,
  easings,
  elevation,
  layers,
  overlineTracking,
  radius,
  toBoxShadow,
  toCubicBezier,
  typeScale,
  type ColorTheme,
  type EasingName,
  type ThemeName,
} from '@delivery/design-tokens';

const HEADER = '/* GENERATED by packages/ui-web/scripts/generate-tokens-css.ts from @delivery/design-tokens. Do not edit. */';
const FONT_STACK = "'Plus Jakarta Sans Variable', 'Plus Jakarta Sans', system-ui, sans-serif";

const rem = (px: number): string => `${px / 16}rem`;
const block = (selector: string, lines: readonly string[]): string =>
  `${selector} {\n${lines.map((line) => `  ${line}`).join('\n')}\n}`;

function colorLines(theme: ColorTheme): string[] {
  return Object.entries(theme).map(([name, value]) => `--color-${name}: ${value};`);
}

function shadowLines(theme: ThemeName): string[] {
  return ([1, 2, 3] as const).map((level) => `--shadow-${level}: ${toBoxShadow(elevation[theme][level])};`);
}

function themeLines(): string[] {
  return [
    '--color-*: initial;',
    ...colorLines(colorThemes.light),
    '--font-*: initial;',
    `--font-sans: ${FONT_STACK};`,
    '--text-*: initial;',
    ...Object.entries(typeScale).flatMap(([step, value]) => [
      `--text-${step}: ${rem(value.size)};`,
      `--text-${step}--line-height: ${rem(value.lineHeight)};`,
      `--text-${step}--letter-spacing: ${value.tracking}em;`,
    ]),
    `--tracking-overline: ${overlineTracking}em;`,
    '--radius-*: initial;',
    ...Object.entries(radius).map(([name, value]) => `--radius-${name}: ${value}px;`),
    '--shadow-*: initial;',
    ...shadowLines('light'),
    '--ease-*: initial;',
    ...(Object.keys(easings) as EasingName[]).map((name) => `--ease-${name}: ${toCubicBezier(name)};`),
    '--breakpoint-*: initial;',
    ...Object.entries(breakpoints).map(([name, value]) => `--breakpoint-${name}: ${rem(value)};`),
    '--spacing: 0.25rem;',
  ];
}

function runtimeLines(): string[] {
  return [
    'color-scheme: light;',
    ...Object.entries(durations).map(([name, value]) => `--duration-${name}: ${value}ms;`),
    ...Object.entries(layers).map(([name, value]) => `--z-${name}: ${value};`),
    ...Object.entries(controlHeight).map(([name, value]) => `--control-${name}: ${rem(value)};`),
    ...Object.entries(borderWidth).map(([name, value]) => `--border-${name}: ${value}px;`),
  ];
}

function darkLines(): string[] {
  return ['color-scheme: dark;', ...colorLines(colorThemes.dark), ...shadowLines('dark')];
}

/** Tailwind 4 theme plus runtime variables; dark mode follows data-theme or the OS preference. */
export function buildTokensCss(): string {
  return [
    HEADER,
    block('@theme static', themeLines()),
    block(':root', runtimeLines()),
    block('[data-theme="dark"]', darkLines()),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', darkLines())
      .split('\n').map((line) => `  ${line}`).join('\n')}\n}`,
    '',
  ].join('\n\n');
}
